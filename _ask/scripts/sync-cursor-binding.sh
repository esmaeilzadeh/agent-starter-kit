#!/usr/bin/env bash
# Generate Cursor-honored projections from .agents/ask/stages (fallback: _ask/agents).
# Merges .agents/ask.local/stages/<stage>.md then _ask/agents/<stage>.local.md.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
if [[ "${ASKIT_TRANSACTION_ACTIVE:-0}" != "1" ]]; then
  if [[ ! -f "$ROOT/_ask/scripts/write-transaction.py" ]]; then
    if [[ -e "$ROOT/.git" ]]; then
      echo "sync-cursor-binding: missing write-transaction.py in Git repository" >&2
      exit 1
    fi
    # shortcut: direct writes are only for disposable non-Git fixtures without the transaction helper.
    export ASKIT_TRANSACTION_ACTIVE=1
  else
    EXTRA_INPUTS=()
    if [[ -n "${ASK_WORK_ID:-}" ]]; then
      EXTRA_INPUTS+=(--input-path "work/$ASK_WORK_ID")
    fi
    exec python3 "$ROOT/_ask/scripts/write-transaction.py" run \
      --root "$ROOT" \
      --path .cursor --path .agents/skills \
      --path .codex/agents --path .claude/agents --path .opencode/agents \
      --input-path _ask/scripts --input-path .agents/ask --input-path .agents/ask.local \
      --input-path _ask/agents --input-path _ask/cursor-commands "${EXTRA_INPUTS[@]}" -- \
      bash "{target}/_ask/scripts/sync-cursor-binding.sh"
  fi
fi
cd "$ROOT"
OUT_SKILLS=".cursor/skills"
OUT_CMDS=".cursor/commands"
python3 "$ROOT/_ask/scripts/sync-codex-skills.py" --check
ASK_ROOT="$ROOT" python3 "$ROOT/_ask/scripts/sync-runtime-agents.py"
mkdir -p "$OUT_SKILLS" "$OUT_CMDS"

if [[ -d .agents/ask/stages ]]; then
  STAGE_DIR=".agents/ask/stages"
  MARKER="# Generated by sync-cursor-binding.sh — do not hand-edit; edit .agents/ask/stages instead."
  SRC_LABEL=".agents/ask/stages"
else
  STAGE_DIR="_ask/agents"
  MARKER="# Generated by sync-cursor-binding.sh — do not hand-edit; edit _ask/agents instead."
  SRC_LABEL="_ask/agents"
fi

for src in "$STAGE_DIR"/[0-9][0-9]-*.md; do
  [[ -f "$src" ]] || continue
  base="$(basename "$src" .md)"
  [[ "$base" == *.local ]] && continue
  local_overlay=".agents/ask.local/stages/${base}.md"
  if [[ ! -f "$local_overlay" ]]; then
    local_overlay="_ask/agents/${base}.local.md"
  fi
  body="$(cat "$src")"
  if [[ -f "$local_overlay" ]]; then
    body="${body}"$'\n\n'"# Local overlay ($(basename "$local_overlay"))"$'\n\n'"$(cat "$local_overlay")"
  fi
  skill_dir="${OUT_SKILLS}/kit-${base}"
  mkdir -p "$skill_dir"
  {
    echo "---"
    echo "name: kit-${base}"
    echo "description: Kit protocol stage ${base}. Generated from ${SRC_LABEL}/${base}.md"
    echo "---"
    echo
    echo "$MARKER"
    echo
    echo "$body"
  } > "${skill_dir}/SKILL.md"

  {
    echo "$MARKER"
    echo
    echo "$body"
  } > "${OUT_CMDS}/${base}.md"
done

for src in _ask/cursor-commands/*.md; do
  [[ -f "$src" ]] || continue
  cp "$src" "${OUT_CMDS}/$(basename "$src")"
done

python3 "$ROOT/_ask/scripts/sync-codex-skills.py"

echo "sync-cursor-binding: generated projections under ${OUT_SKILLS} and ${OUT_CMDS}"
