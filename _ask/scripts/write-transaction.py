#!/usr/bin/env python3
"""Stage client writes, then publish them with recoverable file replacements."""

from __future__ import annotations

import argparse
import fcntl
import hashlib
import json
import os
import shutil
import stat
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

sys.dont_write_bytecode = True
from client_ignores import SHARED, consumer_rules


def fail(message: str) -> None:
    raise ValueError(message)


def digest(path: Path) -> str | None:
    try:
        info = path.lstat()
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(info.st_mode):
        fail(f"unsafe transaction target: {path}")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def identity(path: Path) -> tuple[str, int] | None:
    value = digest(path)
    return None if value is None else (value, stat.S_IMODE(path.stat().st_mode))


def protected(path: str) -> bool:
    return (path.startswith(".agents/ask.local/")
            or path in {"_ask/skills/manifest.yaml", "_ask/bindings/models.yaml",
                        ".agents/verification.yaml"})


def generated(path: Path) -> bool:
    try:
        return "# Generated by sync-cursor-binding.sh" in path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return False


def safe_root(path: Path) -> Path:
    root = path.resolve(strict=True)
    if not root.is_dir():
        fail(f"transaction root is not a directory: {path}")
    return root


def safe_relative(raw: str) -> Path:
    path = Path(raw)
    if path.is_absolute() or not path.parts or any(part in {".", ".."} for part in path.parts):
        fail(f"unsafe transaction path: {raw}")
    return path


def validate_tree(root: Path, rel: Path) -> None:
    current = root
    for part in rel.parts:
        current = current / part
        try:
            info = current.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode):
            fail(f"refusing symlink path component: {current}")
        if current != root / rel and not stat.S_ISDIR(info.st_mode):
            fail(f"path component is not a directory: {current}")
        if not stat.S_ISDIR(info.st_mode) and not stat.S_ISREG(info.st_mode):
            fail(f"refusing special path: {current}")


def files_under(root: Path, rel: Path) -> dict[str, tuple[str, int]]:
    base = root / rel
    if not base.exists():
        return {}
    if base.is_file():
        return {rel.as_posix(): (digest(base) or "", stat.S_IMODE(base.stat().st_mode))}
    result: dict[str, tuple[str, int]] = {}
    for directory, names, files in os.walk(base, followlinks=False):
        here = Path(directory)
        for name in names:
            path = here / name
            if path.is_symlink() or not path.is_dir():
                fail(f"refusing symlink or special path: {path}")
        for name in files:
            path = here / name
            if path.is_symlink() or not path.is_file():
                fail(f"refusing symlink or special path: {path}")
            relative = path.relative_to(root).as_posix()
            result[relative] = (digest(path) or "", stat.S_IMODE(path.stat().st_mode))
    return result


def git_state(root: Path) -> Path:
    result = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--git-path", "askit-transactions"],
        text=True, capture_output=True,
    )
    if result.returncode:
        fail(f"cannot locate private transaction state: {result.stderr.strip()}")
    path = Path(result.stdout.strip())
    if not path.is_absolute():
        path = root / path
    parent = path.parent.resolve(strict=True)
    if parent != path.parent.absolute():
        fail(f"transaction state parent contains a symlink: {path.parent}")
    current = parent
    while current != current.parent:
        if current.is_symlink() or not current.is_dir():
            fail(f"unsafe transaction state parent: {current}")
        current = current.parent
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and (path.is_symlink() or not path.is_dir()):
        fail(f"unsafe transaction state path: {path}")
    path.mkdir(mode=0o700, exist_ok=True)
    os.chmod(path, 0o700)
    if path.stat().st_uid != os.getuid():
        fail(f"transaction state must be owned by the current user: {path}")
    return path


def fsync_dir(path: Path) -> None:
    fd = os.open(path, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def atomic_json(path: Path, data: object) -> None:
    fd, temporary = tempfile.mkstemp(prefix=".journal-", dir=path.parent)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(data, stream, sort_keys=True)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        fsync_dir(path.parent)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def atomic_bytes(path: Path, data: bytes, mode: int = 0o600) -> None:
    fd, temporary = tempfile.mkstemp(prefix=".restore-", dir=path.parent)
    try:
        os.fchmod(fd, mode)
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        fsync_dir(path.parent)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def restore(root: Path, state: Path, journal_path: Path) -> None:
    journal = json.loads(journal_path.read_text(encoding="utf-8"))
    if not isinstance(journal, dict) or journal.get("schema") != "askit-write-transaction/v1":
        fail(f"invalid transaction journal: {journal_path}")
    root_info = root.stat()
    identity_record = journal.get("root")
    if (not isinstance(identity_record, dict)
            or identity_record.get("path") != str(root)
            or identity_record.get("device") != root_info.st_dev
            or identity_record.get("inode") != root_info.st_ino
            or identity_record.get("git_dir") != str(state.parent.resolve())):
        fail(f"transaction journal belongs to another repository: {journal_path}")
    if journal.get("state") == "committed":
        shutil.rmtree(journal_path.parent)
        fsync_dir(state)
        return
    raw_scope = journal.get("scope")
    if not isinstance(raw_scope, list) or not raw_scope or not all(isinstance(v, str) for v in raw_scope):
        fail(f"transaction journal has no write scope: {journal_path}")
    scope = [safe_relative(value) for value in raw_scope]
    if not isinstance(journal.get("files"), list):
        fail(f"invalid transaction file inventory: {journal_path}")
    conflicts: list[str] = []
    for item in journal["files"]:
        if not isinstance(item, dict):
            fail(f"invalid transaction entry: {journal_path}")
        rel = safe_relative(item["path"])
        if not any(rel == path or path in rel.parents for path in scope):
            fail(f"transaction target is outside its write scope: {rel}")
        if rel.parts[0] == ".git":
            fail(f"transaction target points into Git metadata: {rel}")
        validate_tree(root, rel)
        target = root / rel
        current = identity(target)
        before = (item["before_hash"], item["before_mode"]) if item["before_hash"] is not None else None
        after = (item["after_hash"], item["after_mode"]) if item["after_hash"] is not None else None
        if current == before:
            continue
        if current != after:
            conflicts.append(str(target))
            continue
        if item["before_hash"] is None:
            target.unlink(missing_ok=True)
            fsync_dir(target.parent)
            continue
        backup_name = item.get("backup")
        if not isinstance(backup_name, str):
            fail(f"invalid transaction backup path: {journal_path}")
        backup = journal_path.parent / backup_name
        if Path(backup_name).name != backup_name or backup.is_symlink():
            fail(f"invalid transaction backup path: {backup}")
        if digest(backup) != item["before_hash"]:
            fail(f"transaction backup is missing or damaged: {backup}")
        fd, temporary = tempfile.mkstemp(prefix=".restore-", dir=target.parent)
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(backup.read_bytes())
                stream.flush()
                os.fsync(stream.fileno())
            os.chmod(temporary, item["before_mode"])
            os.replace(temporary, target)
            fsync_dir(target.parent)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
    ownership = journal.get("ownership")
    if ownership:
        target = state / "owned-files.json"
        if not isinstance(ownership, dict):
            fail(f"invalid ownership journal: {journal_path}")
        current_hash = digest(target)
        if current_hash == ownership.get("before_hash"):
            pass
        elif current_hash == ownership.get("after_hash"):
            backup_name = ownership.get("backup")
            if not isinstance(backup_name, str) or Path(backup_name).name != backup_name:
                fail(f"invalid ownership backup path: {journal_path}")
            backup = journal_path.parent / backup_name
            if ownership.get("before_hash") is None:
                target.unlink(missing_ok=True)
                fsync_dir(target.parent)
            else:
                if backup.is_symlink() or digest(backup) != ownership["before_hash"]:
                    fail(f"transaction ownership backup is missing or damaged: {backup}")
                atomic_bytes(target, backup.read_bytes())
        else:
            conflicts.append(str(target))
    created_dirs = journal.get("created_dirs", [])
    if not isinstance(created_dirs, list):
        fail(f"invalid directory journal: {journal_path}")
    for name in sorted(created_dirs, key=lambda value: value.count("/"), reverse=True):
        rel = safe_relative(name)
        if (not any(rel == path or path in rel.parents or rel in path.parents for path in scope)
                or rel.parts[0] == ".git"):
            fail(f"transaction directory is outside its write scope: {rel}")
        directory = root / rel
        validate_tree(root, rel)
        try:
            directory.rmdir()
        except OSError:
            pass
    if conflicts:
        fail("transaction recovery conflict; client edits retained: " + ", ".join(conflicts))
    shutil.rmtree(journal_path.parent)
    fsync_dir(state)


def recover_locked(root: Path) -> None:
    state = git_state(root)
    for journal in sorted(state.glob("*/journal.json")):
        if (journal.parent.is_symlink() or not journal.parent.is_dir()
                or journal.parent.stat().st_uid != os.getuid()
                or stat.S_IMODE(journal.parent.stat().st_mode) & 0o077
                or journal.is_symlink() or not journal.is_file()
                or journal.stat().st_uid != os.getuid() or stat.S_IMODE(journal.stat().st_mode) & 0o077):
            fail(f"unsafe transaction journal: {journal}")
        restore(root, state, journal)


def recover(root: Path) -> None:
    state = git_state(root)
    fd = os.open(state / "transaction.lock", os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        recover_locked(root)
    finally:
        os.close(fd)


def shared_ignore_update(before: bytes, after: bytes) -> bool:
    """Only kit-managed ignore lines may change in a consumer-owned file."""
    try:
        return consumer_rules(before) == consumer_rules(after)
    except ValueError:
        return False


def publish(root: Path, stage: Path, paths: list[Path]) -> None:
    before: dict[str, tuple[str, int]] = {}
    after: dict[str, tuple[str, int]] = {}
    for rel in paths:
        validate_tree(root, rel)
        before.update(files_under(root, rel))
        after.update(files_under(stage, rel))
    changes = sorted(path for path in set(before) | set(after) if before.get(path) != after.get(path))
    state = git_state(root)
    ownership_path = state / "owned-files.json"
    try:
        ownership_bytes = ownership_path.read_bytes()
        ownership_stat = ownership_path.lstat()
        if (ownership_path.is_symlink() or not stat.S_ISREG(ownership_stat.st_mode)
                or ownership_stat.st_uid != os.getuid() or stat.S_IMODE(ownership_stat.st_mode) & 0o077):
            fail(f"unsafe installed-file ownership manifest: {ownership_path}")
        ownership = json.loads(ownership_bytes)
        if ownership.get("schema") != "askit-installed-files/v1" or not isinstance(ownership.get("files"), dict):
            fail(f"invalid installed-file ownership manifest: {ownership_path}")
    except FileNotFoundError:
        ownership_bytes = None
        ownership = {"schema": "askit-installed-files/v1", "files": {}}
    known = ownership["files"]
    if not isinstance(known, dict):
        fail(f"invalid installed-file ownership manifest: {ownership_path}")
    next_files = {name: value for name, value in known.items()
                  if not name.startswith(".cursor/") or f"/{name}" in SHARED or generated(root / name)}
    for name in changes:
        rel = safe_relative(name)
        target = root / rel
        if protected(name) and name in before:
            fail(f"refusing to replace project-owned setting: {target}")
        prior = before.get(name)
        new = after.get(name)
        shared_ignore = bool(name == '.gitignore' and prior and new and prior[1] == new[1]
                             and shared_ignore_update(target.read_bytes(), (stage / rel).read_bytes()))
        if prior and not shared_ignore:
            recorded = known.get(name)
            if recorded is not None and recorded != {"sha256": prior[0], "mode": prior[1]}:
                fail(f"installed file was edited since the last update: {target}")
            if recorded is None and not generated(target):
                fail(f"unowned destination collision: {target}")
        if shared_ignore:
            next_files.pop(name, None)
        elif new:
            next_files[name] = {"sha256": new[0], "mode": new[1]}
        else:
            next_files.pop(name, None)
    for name, current in after.items():
        if protected(name):
            continue
        if name in changes and name not in before:
            next_files[name] = {"sha256": current[0], "mode": current[1]}
        elif name in before and generated(root / name):
            next_files[name] = {"sha256": current[0], "mode": current[1]}
    ownership_after = (json.dumps({"schema": "askit-installed-files/v1", "files": next_files},
                                  sort_keys=True, indent=2) + "\n").encode()
    if not changes:
        if ownership_bytes is None:
            atomic_bytes(ownership_path, ownership_after)
        return
    journal_dir = state / uuid.uuid4().hex
    journal_dir.mkdir(mode=0o700)
    files = []
    created_dirs: set[str] = set()
    try:
        for index, name in enumerate(changes):
            rel = safe_relative(name)
            target = root / rel
            validate_tree(root, rel)
            parent = target.parent
            missing: list[Path] = []
            while parent != root and not parent.exists():
                missing.append(parent)
                parent = parent.parent
            created_dirs.update(path.relative_to(root).as_posix() for path in missing)
            source = stage / rel
            old = before.get(name)
            new = after.get(name)
            backup_name = f"{index}.bak"
            if old:
                backup = journal_dir / backup_name
                backup.write_bytes(target.read_bytes())
                os.chmod(backup, 0o600)
                with backup.open("rb") as stream:
                    os.fsync(stream.fileno())
            files.append({
                "path": name,
                "before_hash": old[0] if old else None,
                "before_mode": old[1] if old else None,
                "after_hash": new[0] if new else None,
                "after_mode": new[1] if new else None,
                "backup": backup_name,
            })
        fsync_dir(journal_dir)
        ownership_backup = "ownership.bak"
        if ownership_bytes is not None:
            (journal_dir / ownership_backup).write_bytes(ownership_bytes)
            os.chmod(journal_dir / ownership_backup, 0o600)
            with (journal_dir / ownership_backup).open("rb") as stream:
                os.fsync(stream.fileno())
        fsync_dir(journal_dir)
        journal = journal_dir / "journal.json"
        atomic_json(journal, {
            "schema": "askit-write-transaction/v1", "files": files,
            "created_dirs": sorted(created_dirs),
            "root": {
                "path": str(root), "device": root.stat().st_dev, "inode": root.stat().st_ino,
                "git_dir": str(state.parent.resolve()),
            },
            "scope": [path.as_posix() for path in paths],
            "ownership": {
                "before_hash": hashlib.sha256(ownership_bytes).hexdigest() if ownership_bytes else None,
                "after_hash": hashlib.sha256(ownership_after).hexdigest(),
                "backup": ownership_backup,
            },
        })
        for item in files:
            target = root / item["path"]
            expected = ((item["before_hash"], item["before_mode"])
                        if item["before_hash"] is not None else None)
            if identity(target) != expected:
                fail(f"client file changed during transaction preflight: {target}")
            target.parent.mkdir(parents=True, exist_ok=True)
            validate_tree(root, safe_relative(item["path"]))
            if item["after_hash"] is None:
                target.unlink(missing_ok=True)
            else:
                source = stage / item["path"]
                fd, temporary = tempfile.mkstemp(prefix=".publish-", dir=target.parent)
                try:
                    with os.fdopen(fd, "wb") as stream:
                        stream.write(source.read_bytes())
                        stream.flush()
                        os.fsync(stream.fileno())
                    os.chmod(temporary, item["after_mode"])
                    os.replace(temporary, target)
                finally:
                    if os.path.exists(temporary):
                        os.unlink(temporary)
            fsync_dir(target.parent)
        for item in files:
            if item["after_hash"] is not None:
                continue
            rel = Path(item["path"])
            scopes = [path for path in paths if path in rel.parents]
            if not scopes:
                continue
            scope = max(scopes, key=lambda path: len(path.parts))
            directory = (root / rel).parent
            while directory != root / scope:
                staged = stage / directory.relative_to(root)
                if staged.exists():
                    break
                try:
                    directory.rmdir()
                    fsync_dir(directory.parent)
                except OSError:
                    break
                directory = directory.parent
        fd, temporary = tempfile.mkstemp(prefix=".owned-files-", dir=state)
        try:
            current_ownership_hash = digest(ownership_path)
            expected_ownership_hash = hashlib.sha256(ownership_bytes).hexdigest() if ownership_bytes else None
            if current_ownership_hash != expected_ownership_hash:
                fail(f"installed-file ownership changed during transaction: {ownership_path}")
            os.fchmod(fd, 0o600)
            with os.fdopen(fd, "wb") as stream:
                stream.write(ownership_after)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, ownership_path)
            fsync_dir(state)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        journal_data = json.loads(journal.read_text(encoding="utf-8"))
        journal_data["state"] = "committed"
        atomic_json(journal, journal_data)
        shutil.rmtree(journal_dir)
        fsync_dir(state)
    except BaseException:
        if (journal_dir / "journal.json").exists():
            try:
                restore(root, state, journal_dir / "journal.json")
            except Exception as recovery_error:
                print(f"write-transaction: recovery retained: {recovery_error}", file=sys.stderr)
        else:
            shutil.rmtree(journal_dir, ignore_errors=True)
        raise


def run(args: argparse.Namespace) -> int:
    root = safe_root(Path(args.root))
    paths = [safe_relative(path) for path in args.path]
    input_paths = list(dict.fromkeys(paths + [safe_relative(path) for path in args.input_path]))
    input_paths = [path for path in input_paths
                   if not any(path != parent and parent in path.parents for parent in input_paths)]
    for path in input_paths:
        validate_tree(root, path)
        files_under(root, path)
    state = git_state(root)
    lock_path = state / "transaction.lock"
    fd = os.open(lock_path, os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        recover_locked(root)
        with tempfile.TemporaryDirectory(prefix="askit-stage-", dir=root.parent) as temp:
            stage = Path(temp) / "project"
            stage.mkdir()
            for rel in input_paths:
                source = root / rel
                target = stage / rel
                if source.is_dir():
                    shutil.copytree(source, target, symlinks=True)
                elif source.is_file():
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(source, target)
            git_marker = root / ".git"
            if git_marker.is_dir():
                (stage / ".git").symlink_to(git_marker.resolve(), target_is_directory=True)
            elif git_marker.is_file():
                git_dir = subprocess.run(
                    ["git", "-C", str(root), "rev-parse", "--absolute-git-dir"],
                    text=True, capture_output=True, check=True,
                ).stdout.strip()
                (stage / ".git").write_text(f"gitdir: {git_dir}\n", encoding="utf-8")
            else:
                fail(f"transaction root has no Git metadata: {root}")
            env = dict(os.environ, ASKIT_TRANSACTION_ACTIVE="1")
            env.pop("GIT_DIR", None)
            env.pop("GIT_WORK_TREE", None)
            result = subprocess.run(args.command_stage(stage), cwd=root, env=env)
            if result.returncode:
                return result.returncode
            publish(root, stage, paths)
    finally:
        os.close(fd)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="action", required=True)
    command = sub.add_parser("run")
    command.add_argument("--root", required=True)
    command.add_argument("--path", action="append", required=True)
    command.add_argument("--input-path", action="append", default=[])
    command.add_argument("command", nargs=argparse.REMAINDER)
    recovery = sub.add_parser("recover")
    recovery.add_argument("--root", required=True)
    args = parser.parse_args()
    try:
        root = safe_root(Path(args.root))
        if args.action == "recover":
            recover(root)
            return 0
        command_args = args.command[1:] if args.command[:1] == ["--"] else args.command
        if not command_args:
            fail("run requires a command after --")
        args.command = command_args
        args.command_stage = lambda stage: [
            arg.replace("{target}", str(stage)) for arg in command_args
        ]
        return run(args)
    except (OSError, ValueError, TypeError, KeyError, AttributeError, json.JSONDecodeError) as error:
        print(f"write-transaction: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
