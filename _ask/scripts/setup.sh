{"command":"uvx","args":["mcp-atlassian"],"env":{"JIRA_URL":"${env:JIRA_URL}","JIRA_PERSONAL_TOKEN":"${env:JIRA_PERSONAL_TOKEN}"}}
JSON
)"
      _write_tracker_md jira "$ASK_TRACKER_URL"
